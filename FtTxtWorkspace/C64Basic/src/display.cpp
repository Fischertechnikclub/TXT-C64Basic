void TextDisplay::print(char c)
{ uint8_t firstRow = MAXROWS-Rows();
  switch(c)
  { case 5:  fg = WHITE; break; //white
    case 13: col=0; //the carriage return
             reverse = false;
    	     row++; if(row==MAXROWS) scroll(); //actually a linefeed //
             break;
    case 17: //row++; if(row==MAXROWS) row = firstRow;
             row++; if(row==MAXROWS) scroll();
             break;
    case 14: upgfx = false; break;
    case 18: reverse = true; break;
    case 19: row = firstRow; col = 0; break;//home
    case 28: fg = RED; break;//red
    case 29: if(col<COLUMNS-1) col++; break;
    case 30: fg = GREEN; break;//green
    case 31: fg = BLUE; break;//blue
    case 129: fg = ORANGE; break;//orange
    case 142: upgfx = true; break;
    case 144: fg = BLACK; break;//black
    case 145: if(row>firstRow) row--; break;
    case 146: reverse = false; break;
    case 147: clear(); break;
    case 149: fg = BROWN; break;
    case 150: fg = PINK; break;
    case 151: fg = dGREY; break;
    case 152: fg = mGREY; break;
    case 153: fg = ltGREEN; break;
    case 154: fg = ltBLUE; break;
    case 155: fg = ltGREY; break;
    case 156: fg = PURPLE; break;
    case 157: if(col>0)col--; break;
    case 158: fg = YELLOW; break;
    case 159: fg = CYAN; break;
    default:
#if DIRECTTEXT==1
    	      if(writeChar(row, col, c, upgfx, reverse))
    	      { col++;
                if(col==COLUMNS)
                { col=0; row++;
                  if(row==Rows()) scroll();
                }
    	      }
#else
    	      if((c&0x7F) >= 32)
    	      { if(c&0x80) c = (c&0x3F) | 0x40; //move bit 7 into 6 to map petscii to screenRam format
    	        else c &= 0x3F;
    	    	if(reverse) c |= 0x80;
    	    	/*if(col==COLUMNS) //late scrolling
                { col=0; row++;
                  if(row==MAXROWS) scroll();
    	    	}*/
    	    	screenRam[row][col] = c;
    	    	colorRam[row][col] = fg;
    	    	col++;
    	    	if(col==COLUMNS) //early scrolling
                { col=0; row++;
                  if(row==MAXROWS) scroll();
    	    	}
    	      }
#endif
             break;
  }
}

void TextDisplay::scroll() // { row=0; firstRow=25-rows + (firstRow+1)%rows;}
{   if(Rows()==0) return;
	row = MAXROWS-1; //scrolling is always on the last row
	uint8_t firstRow = MAXROWS - Rows();
	if(Rows() > 1)
	{ memmove(screenRam[firstRow], screenRam[firstRow+1], COLUMNS*(Rows()-1)*sizeof(uint8_t));
	  memmove(colorRam[firstRow], colorRam[firstRow+1], COLUMNS*(Rows()-1)*sizeof(color_t));
	}
	memset(screenRam[row], ' ', COLUMNS*sizeof(uint8_t));
	for (int c= 0; c < COLUMNS; c++) colorRam[row][c] = bg;
}

